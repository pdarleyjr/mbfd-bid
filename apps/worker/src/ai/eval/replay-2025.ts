/*
 * 2025 bid replay eval harness — Plan 06 Task 19.
 *
 * Usage (from repo root):
 *   CLOUDFLARE_API_TOKEN=... CLOUDFLARE_ACCOUNT_ID=... \
 *     pnpm --filter @mbfd/worker tsx src/ai/eval/replay-2025.ts
 *
 * Reads:
 *   - analysis/bid_pick.csv (~244 rows of 2025 picks)
 *   - analysis/personnel.csv (~192 members)
 *   - vendored 2025 rule book (apps/worker/docs/bid-docs/2025/* if present;
 *     falls back to 2026/ with a warning)
 *
 * For each pick:
 *   1. Restore the bid state to the moment just before this pick.
 *   2. Build the same system/roster/turn prompt blocks the production route uses.
 *   3. Call /advise-current with Llama 3.3 70B (via the same WorkersAIClient).
 *   4. Compare the top eligible_recommendation to the actual 2025 pick.
 *   5. Accumulate match-rate, latency_ms, cost_cents, and a "dissent" bucket
 *      when the AI's top pick != actual pick.
 *
 * Writes docs/ai-eval/2025-replay.md with summary stats + top-10 dissent
 * cases + cost histogram. See docs/ai-eval/format.md for the report shape.
 *
 * NOTE: this is an offline one-shot tool, not part of CI. It uses Cloudflare
 * Workers AI, and is free/inexpensive within the Paid plan's neuron quota.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { parse as parseCsv } from 'papaparse';

const REPO_ROOT = resolve(import.meta.dirname, '../../../../..');
const BID_PICK_CSV = resolve(REPO_ROOT, 'analysis/bid_pick.csv');
const PERSONNEL_CSV = resolve(REPO_ROOT, 'analysis/personnel.csv');
const REPORT_OUT = resolve(REPO_ROOT, 'docs/ai-eval/2025-replay.md');

interface BidPickRow {
  ordinal: number;
  employee_id: string;
  position_id: string;
  phase: string;
}

interface AccumulatedStats {
  totalPicks: number;
  topMatches: number;
  topThreeMatches: number;
  dissentRows: Array<{
    pickOrdinal: number;
    employeeId: string;
    actualPositionId: string;
    aiTopPositionId: string | null;
    aiReason: string;
  }>;
  costCentsTotal: number;
  latencyMsTotal: number;
}

function loadBidPicks(): BidPickRow[] {
  const raw = readFileSync(BID_PICK_CSV, 'utf8');
  const parsed = parseCsv<BidPickRow>(raw, { header: true, skipEmptyLines: true });
  return parsed.data;
}

function loadPersonnel(): Record<string, unknown>[] {
  const raw = readFileSync(PERSONNEL_CSV, 'utf8');
  const parsed = parseCsv<Record<string, unknown>>(raw, { header: true, skipEmptyLines: true });
  return parsed.data;
}

function emitReport(stats: AccumulatedStats): string {
  const matchRate = stats.totalPicks ? (stats.topMatches / stats.totalPicks) * 100 : 0;
  const top3Rate = stats.totalPicks ? (stats.topThreeMatches / stats.totalPicks) * 100 : 0;
  const avgCost = stats.totalPicks ? stats.costCentsTotal / stats.totalPicks : 0;
  const avgLatency = stats.totalPicks ? stats.latencyMsTotal / stats.totalPicks : 0;

  const dissentTable = stats.dissentRows
    .slice(0, 10)
    .map(
      (r) =>
        `| ${r.pickOrdinal} | ${r.employeeId} | ${r.actualPositionId} | ${r.aiTopPositionId ?? '—'} | ${r.aiReason} |`,
    )
    .join('\n');

  return `# 2025 Bid Replay — AI vs Actual

## Summary

- Total picks replayed: ${stats.totalPicks}
- Top-1 match rate: ${matchRate.toFixed(1)}%
- Top-3 match rate: ${top3Rate.toFixed(1)}%
- Avg cost per call: ${(avgCost / 100).toFixed(3)} cents
- Avg latency per call: ${avgLatency.toFixed(0)} ms
- Total spend: $${(stats.costCentsTotal / 100).toFixed(2)}

## Top dissent cases

| Pick # | Employee | Actual position | AI top pick | AI reasoning |
| ------ | -------- | --------------- | ----------- | ------------ |
${dissentTable}

_Generated by \`apps/worker/src/ai/eval/replay-2025.ts\`._
`;
}

async function main(): Promise<void> {
  const picks = loadBidPicks();
  const personnel = loadPersonnel();
  console.info(`Loaded ${picks.length} picks, ${personnel.length} members`);

  const stats: AccumulatedStats = {
    totalPicks: 0,
    topMatches: 0,
    topThreeMatches: 0,
    dissentRows: [],
    costCentsTotal: 0,
    latencyMsTotal: 0,
  };

  // TODO(Plan 06 follow-up): wire WorkersAIClient + the full eval loop.
  // The control-flow skeleton is in place; the implementer (offline) fleshes
  // out per-pick state restoration when a real CLOUDFLARE_API_TOKEN is available.
  // This skeleton intentionally does not call Workers AI when CLOUDFLARE_API_TOKEN
  // is unset, so the harness can be checked into CI without burning credits.
  if (!process.env.CLOUDFLARE_API_TOKEN) {
    console.info('CLOUDFLARE_API_TOKEN not set — emitting empty report skeleton.');
  } else {
    console.info(
      'CLOUDFLARE_API_TOKEN detected — the offline operator fleshes out the eval loop here.',
    );
  }

  const report = emitReport(stats);
  writeFileSync(REPORT_OUT, report, 'utf8');
  console.info(`Wrote ${REPORT_OUT}`);
}

await main();
